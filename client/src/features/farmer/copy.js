/** "Thu 23 Oct" / "ਵੀਰ, 23 ਅਕਤੂਬਰ". */
export function shortDate(value, language = 'en') {
  const d = new Date(value)
  const names = DATE_NAMES[language] ?? DATE_NAMES.en
  const day = names.days[d.getDay()]
  const month = names.months[d.getMonth()]
  return language === 'en' ? `${day} ${d.getDate()} ${month}` : `${day}, ${d.getDate()} ${month}`
}
